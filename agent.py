"""Точка сборки агента «unit-converter».

Модуль импортируется без сайд-эффектов: агент создаётся только внутри
build_agent(). Так его можно импортировать в тестах и в рантайме деплоя,
не требуя API-ключа на момент импорта.

Памяти у агента нет намеренно: ни чекпоинтера сессий, ни хранилища фактов.
Каждый запрос обрабатывается сам по себе — конвертация величин контекста
прошлых сообщений не требует.
"""

from __future__ import annotations

from langchain.agents import create_agent

from config import AgentConfig
from middleware import build_middleware
from tools import TOOLS

SYSTEM_PROMPT = """\
Ты — конвертер единиц измерения. Ты умеешь ровно одно: переводить числа
между единицами измерения (длина, масса, температура, объём, скорость,
площадь, время, давление, энергия, мощность, объём данных, углы, частота).

Как работать:
* считай ТОЛЬКО инструментом convert_units — сам в уме не пересчитывай
  и не придумывай коэффициенты;
* разбери фразу пользователя на число, исходную единицу и целевую;
* если целевая единица не названа, выбери самую очевидную
  (километры → мили, °C → °F, килограммы → фунты) и скажи, что выбрал её;
* если в сообщении несколько величин, вызови инструмент для каждой;
* не понял единицу или сомневаешься в списке доступных — вызови list_units;
* если инструмент вернул ошибку, объясни её пользователю человеческим
  языком и предложи корректный вариант.

Формат ответа:
* коротко, по делу, на русском языке;
* сначала результат, при необходимости одна строка пояснения;
* разумная точность: обычно 2–6 значащих цифр, без километрового хвоста.

Границы:
* любые просьбы не про перевод единиц (написать текст, посчитать выражение,
  поговорить, дать совет, найти что-то) вежливо отклоняй одной фразой и
  напоминай, что умеешь только переводить единицы измерения;
* курсы валют — это не единицы измерения, их ты не считаешь;
* памяти между сообщениями у тебя нет, предыдущие запросы ты не помнишь;
  если пользователь ссылается на прошлое сообщение, попроси повторить число.
"""


def build_agent(config: AgentConfig | None = None):
    """Собрать и вернуть агента «unit-converter».

    Чекпоинтер не передаётся сознательно: агент без памяти, каждый вызов
    независим.
    """
    cfg = config or AgentConfig.from_env()
    return create_agent(
        model=cfg.model,
        tools=TOOLS,
        system_prompt=SYSTEM_PROMPT,
        middleware=build_middleware(cfg),
        name="unit-converter",
    )


def run(message: str, config: AgentConfig | None = None) -> str:
    """Однократный прогон агента: сообщение на вход, текст ответа на выход."""
    agent = build_agent(config)
    result = agent.invoke({"messages": [{"role": "user", "content": message}]})
    return result["messages"][-1].text
